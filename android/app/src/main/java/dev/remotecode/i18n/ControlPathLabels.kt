private val liveSessionNote = Regex("live\\ として保存されている会話は\\ ([0-9]+)\\ 件です。PC\\ の記録表示と\\ ACP\\ 実行を保存フラグだけでは区別できないため、経路別の件数は確定できません。")
private val englishLiveSessionNote = Regex(
    Regex.escape("There are ") + "([0-9]+)" + Regex.escape(" conversations saved as live. Because transcript viewing and ACP execution cannot be distinguished by saved flags alone, exact counts by path cannot be determined."),
)

fun localizedControlPathText(value: String, strings: AppStringResolver = applicationStrings): String {
    serverMessageCandidates(value).firstNotNullOfOrNull { controlPathCatalog[it] }?.let { return strings.text(it) }
    val liveNote = liveSessionNote.matchEntire(value) ?: englishLiveSessionNote.matchEntire(value)
    if (liveNote != null) return strings.text(R.string.control_path_catalog_live_note, liveNote.groupValues[1])
    return value
}
